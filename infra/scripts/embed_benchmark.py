# ─── Stage 1: corpus ──────────────────────────────────────────────────────────

def stage_corpus() -> None:
    """Download non-garbage chunks from Supabase into corpus.json."""
    print(f"[corpus] fetching from {SUPABASE_URL} ...")
    chunks: list[dict[str, Any]] = []
    page = 0
    page_size = 1000
    while True:
        r = requests.get(
            f"{SUPABASE_URL}/rest/v1/rag_chunks",
            params={
                "select": "id,source_id,source_title,chunk_text,topic_tags,language",
                "order":  "id",
                "limit":  page_size,
                "offset": page * page_size,
            },
            headers={
                "apikey":        SUPABASE_KEY,
                "Authorization": f"Bearer {SUPABASE_KEY}",
            },
            timeout=60,
        )
        r.raise_for_status()
        batch = r.json()
        if not batch:
            break
        chunks.extend(batch)
        page += 1
        if len(batch) < page_size:
            break

    before = len(chunks)
    chunks = [c for c in chunks if c["source_id"] not in EXCLUDED_SOURCES]
    print(f"[corpus] {before} fetched, {len(chunks)} kept after excluding {EXCLUDED_SOURCES}")
    CORPUS_PATH.write_text(json.dumps(chunks, ensure_ascii=False))
    by_src: dict[str, int] = {}
    for c in chunks:
        by_src[c["source_id"]] = by_src.get(c["source_id"], 0) + 1
    print("[corpus] by source:")
    for k, v in sorted(by_src.items(), key=lambda kv: -kv[1]):
        print(f"          {v:>5}  {k}")
    print(f"[corpus] saved → {CORPUS_PATH}")


# ─── Stage 2: golden set ──────────────────────────────────────────────────────

GOLDEN_PROMPT = """Ты помогаешь оценить качество retrieval-системы для образовательной платформы по математике для Data Science.

Дан фрагмент учебного текста. Сформулируй один реалистичный вопрос студента, на который этот фрагмент даёт ответ.

Требования к вопросу:
- На русском языке
- Тон студента (не преподавателя), как будто человек учится сам
- Естественная формулировка — НЕ цитируй текст дословно
- 5-20 слов
- Конкретный, не «расскажи всё про матрицы»
- Без префиксов вроде «Вопрос:», только сам текст вопроса

Фрагмент:
\"\"\"
{chunk}
\"\"\"

Верни только вопрос, одной строкой, без кавычек."""


def call_deepseek(prompt: str, max_tokens: int = 120) -> str:
    r = requests.post(
        "https://api.deepseek.com/chat/completions",
        headers={
            "Authorization": f"Bearer {DEEPSEEK_KEY}",
            "Content-Type":  "application/json",
        },
        json={
            "model":       "deepseek-chat",
            "messages":    [{"role": "user", "content": prompt}],
            "temperature": 0.3,
            "max_tokens":  max_tokens,
        },
        timeout=60,
    )
    r.raise_for_status()
    return r.json()["choices"][0]["message"]["content"].strip()


def stage_goldenset() -> None:
    """Generate (query, ground_truth_chunk_id) pairs via DeepSeek."""
    if not CORPUS_PATH.exists():
        sys.exit("[goldenset] corpus.json missing — run --stage corpus first")
    chunks: list[dict[str, Any]] = json.loads(CORPUS_PATH.read_text())

    # Stratify across sources so we don't sample only from the largest one.
    rng = np.random.default_rng(RANDOM_SEED)
    by_src: dict[str, list[dict[str, Any]]] = {}
    for c in chunks:
        by_src.setdefault(c["source_id"], []).append(c)

    target_per_src: dict[str, int] = {}
    sources = list(by_src.keys())
    total_remaining = GOLDEN_SET_SIZE
    # Proportional to size, but min 3 per source if source has >= 3 chunks
    sizes = np.array([len(by_src[s]) for s in sources])
    proportions = sizes / sizes.sum()
    raw = (proportions * GOLDEN_SET_SIZE).round().astype(int)
    raw = np.maximum(raw, np.minimum(sizes, 3))
    diff = GOLDEN_SET_SIZE - raw.sum()
    if diff != 0:
        idx = np.argsort(-sizes)
        i = 0
        step = 1 if diff > 0 else -1
        while diff != 0:
            j = idx[i % len(idx)]
            if step > 0 or raw[j] > 1:
                raw[j] += step
                diff -= step
            i += 1
    target_per_src = {s: int(n) for s, n in zip(sources, raw)}

    print("[goldenset] sampling plan:")
    for s, n in target_per_src.items():
        print(f"           {n:>3} from {s}")

    # Also exclude very short chunks (less than 400 chars usually = ToC noise)
    sampled: list[dict[str, Any]] = []
    for src, n in target_per_src.items():
        pool = [c for c in by_src[src] if len(c["chunk_text"]) >= 400]
        if len(pool) < n:
            pool = by_src[src]
        idx = rng.choice(len(pool), size=min(n, len(pool)), replace=False)
        for i in idx:
            sampled.append(pool[i])

    # Existing golden set: resume so we don't rebill DeepSeek
    existing: list[dict[str, Any]] = []
    if GOLDEN_PATH.exists():
        existing = json.loads(GOLDEN_PATH.read_text())
        done_ids = {p["ground_truth_id"] for p in existing}
        sampled = [c for c in sampled if c["id"] not in done_ids]
        print(f"[goldenset] resuming: {len(existing)} existing pairs, {len(sampled)} new to generate")

    for i, chunk in enumerate(sampled, 1):
        snippet = chunk["chunk_text"][:1800]
        try:
            q = call_deepseek(GOLDEN_PROMPT.format(chunk=snippet))
        except Exception as e:
            print(f"[goldenset] DeepSeek error on chunk {chunk['id']}: {e}")
            continue
        q = q.replace("Вопрос:", "").strip().strip('"').strip("«»").strip()
        if not q or len(q) > 250:
            print(f"[goldenset]   skipped (bad output): {q!r}")
            continue
        existing.append({
            "query":            q,
            "ground_truth_id":  chunk["id"],
            "source_id":        chunk["source_id"],
            "source_title":     chunk["source_title"],
        })
        print(f"[goldenset] [{i}/{len(sampled)}] {chunk['source_id']:>22} → {q}")
        GOLDEN_PATH.write_text(json.dumps(existing, ensure_ascii=False, indent=2))

    print(f"[goldenset] saved {len(existing)} pairs → {GOLDEN_PATH}")


# ─── Stage 3: run models ──────────────────────────────────────────────────────

def metrics_for_ranks(ranks: list[int | None], k_values: list[int]) -> dict[str, float]:
    """ranks: position of ground truth in retrieved list (1-indexed) or None if not in top-K."""
    n = len(ranks)
    out: dict[str, float] = {}
    for k in k_values:
        hits = sum(1 for r in ranks if r is not None and r <= k)
        out[f"recall@{k}"] = hits / n
    # MRR@10
    mrr_vals = [1.0 / r if r is not None and r <= 10 else 0.0 for r in ranks]
    out["mrr@10"] = float(np.mean(mrr_vals))
    # NDCG@10 with single relevant doc — equals 1/log2(rank+1) if found
    ndcg_vals = [1.0 / math.log2(r + 1) if r is not None and r <= 10 else 0.0 for r in ranks]
    out["ndcg@10"] = float(np.mean(ndcg_vals))
    return out


def pick_device() -> str:
    import torch
    if torch.backends.mps.is_available() and torch.backends.mps.is_built():
        return "mps"
    if torch.cuda.is_available():
        return "cuda"
    return "cpu"


def run_model(spec: ModelSpec, corpus: list[dict[str, Any]], golden: list[dict[str, Any]]) -> dict[str, Any]:
    from sentence_transformers import SentenceTransformer

    device = os.environ.get("BENCH_DEVICE") or pick_device()
    proc = psutil.Process()
    rss_before = proc.memory_info().rss
    print(f"[{spec.key}] loading {spec.hf_id} on device={device} ...")
    t0 = time.perf_counter()
    model = SentenceTransformer(spec.hf_id, trust_remote_code=spec.trust_remote_code, device=device)
    load_seconds = time.perf_counter() - t0
    rss_after_load = proc.memory_info().rss
    print(f"[{spec.key}] loaded in {load_seconds:.1f}s, +{(rss_after_load-rss_before)/1e6:.0f} MB RAM")

    # Sanity: model dim
    actual_dim = model.get_sentence_embedding_dimension()
    if actual_dim != spec.dim:
        print(f"[{spec.key}] WARNING: expected dim {spec.dim}, got {actual_dim}")

    doc_texts = [spec.doc_prefix + c["chunk_text"] for c in corpus]
    print(f"[{spec.key}] embedding {len(doc_texts)} chunks ...")
    t0 = time.perf_counter()
    doc_embs = model.encode(
        doc_texts,
        batch_size=16,
        show_progress_bar=True,
        normalize_embeddings=True,
        convert_to_numpy=True,
    )
    encode_corpus_seconds = time.perf_counter() - t0
    rss_after_encode = proc.memory_info().rss
    print(f"[{spec.key}] corpus encoded in {encode_corpus_seconds:.1f}s")

    q_texts = [spec.query_prefix + p["query"] for p in golden]
    t0 = time.perf_counter()
    q_embs = model.encode(
        q_texts,
        batch_size=16,
        show_progress_bar=False,
        normalize_embeddings=True,
        convert_to_numpy=True,
    )
    encode_queries_seconds = time.perf_counter() - t0
    latency_ms_per_query = (encode_queries_seconds / len(q_texts)) * 1000

    # Retrieval: cosine via dot (already normalized)
    sims = q_embs @ doc_embs.T  # (Q, N)
    top_k_idx = np.argsort(-sims, axis=1)[:, :TOP_K]
    chunk_id_by_pos = [c["id"] for c in corpus]

    ranks: list[int | None] = []
    for qi, gold in enumerate(golden):
        gt = gold["ground_truth_id"]
        found = None
        for pos, idx in enumerate(top_k_idx[qi], 1):
            if chunk_id_by_pos[idx] == gt:
                found = pos
                break
        ranks.append(found)

    m = metrics_for_ranks(ranks, k_values=[1, 3, 5, 10])
    peak_mem_mb = (rss_after_encode - rss_before) / 1e6

    result = {
        "model_key":               spec.key,
        "hf_id":                   spec.hf_id,
        "dim":                     int(actual_dim),
        "device":                  device,
        "notes":                   spec.notes,
        "metrics":                 m,
        "load_seconds":            round(load_seconds, 2),
        "encode_corpus_seconds":   round(encode_corpus_seconds, 2),
        "latency_ms_per_query":    round(latency_ms_per_query, 2),
        "peak_added_ram_mb":       round(peak_mem_mb, 0),
        "n_corpus":                len(corpus),
        "n_queries":               len(golden),
        "ranks":                   ranks,
    }
    out_path = RESULTS_DIR / f"{spec.key}.json"
    out_path.write_text(json.dumps(result, ensure_ascii=False, indent=2))
    print(f"[{spec.key}] {m} → {out_path}")

    # Free memory before loading next model
    del model, doc_embs, q_embs, sims, top_k_idx
    gc.collect()
    return result


def stage_models(only: list[str] | None) -> None:
    if not CORPUS_PATH.exists():
        sys.exit("[models] corpus.json missing — run --stage corpus first")
    if not GOLDEN_PATH.exists():
        sys.exit("[models] golden_set.json missing — run --stage goldenset first")

    corpus = json.loads(CORPUS_PATH.read_text())
    golden = json.loads(GOLDEN_PATH.read_text())
    print(f"[models] corpus={len(corpus)} chunks, golden={len(golden)} queries")

    for spec in MODELS:
        if only and spec.key not in only:
            continue
        out_path = RESULTS_DIR / f"{spec.key}.json"
        if out_path.exists() and not only:
            print(f"[models] {spec.key} already done — skip (delete {out_path} to redo)")
            continue
        try:
            run_model(spec, corpus, golden)
        except Exception as e:
            print(f"[models] {spec.key} FAILED: {e}")
            import traceback; traceback.print_exc()


# ─── Stage 4: report ──────────────────────────────────────────────────────────

def stage_report() -> None:
    results: list[dict[str, Any]] = []
    for spec in MODELS:
        p = RESULTS_DIR / f"{spec.key}.json"
        if p.exists():
            results.append(json.loads(p.read_text()))
    if not results:
        sys.exit("[report] no result files yet")

    # Sort by NDCG@10 desc — main quality metric
    results.sort(key=lambda r: -r["metrics"]["ndcg@10"])

    lines: list[str] = []
    lines.append("# Embedding model benchmark — MindFlow corpus")
    lines.append("")
    lines.append(f"Сравнение {len(results)} бесплатных open-source эмбеддеров на реальном корпусе RAG MindFlow.")
    lines.append("")
    n_corpus = results[0]["n_corpus"]
    n_queries = results[0]["n_queries"]
    lines.append(f"- Корпус: **{n_corpus} чанков** (исключены 150 мусорных чанков `auto_gelfand1971ru`)")
    lines.append(f"- Golden set: **{n_queries} пар (query, ground-truth chunk)**, автогенерация через DeepSeek")
    lines.append(f"- Метрики: Recall@K, MRR@10, NDCG@10 на CPU MacBook")
    lines.append("")
    lines.append("## Результаты")
    lines.append("")
    lines.append("| Модель | Dim | R@1 | R@5 | R@10 | MRR@10 | NDCG@10 | Latency, мс/q | +RAM, МБ |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for r in results:
        m = r["metrics"]
        lines.append(
            f"| `{r['model_key']}` ({r['hf_id'].split('/')[-1]}) "
            f"| {r['dim']} "
            f"| {m['recall@1']:.2f} "
            f"| {m['recall@5']:.2f} "
            f"| {m['recall@10']:.2f} "
            f"| {m['mrr@10']:.3f} "
            f"| {m['ndcg@10']:.3f} "
            f"| {r['latency_ms_per_query']:.1f} "
            f"| {r['peak_added_ram_mb']:.0f} |"
        )
    lines.append("")
    winner = results[0]
    lines.append(f"## Победитель: `{winner['model_key']}`")
    lines.append("")
    lines.append(f"**Модель:** `{winner['hf_id']}` ({winner['dim']}D)")
    lines.append("")
    lines.append(f"**Почему она:** {winner['notes']}.")
    lines.append("")
    lines.append("Аргументы по цифрам (см. таблицу выше):")
    baseline = next((r for r in results if r["model_key"] == "e5-small"), None)
    if baseline and baseline is not winner:
        delta_ndcg = winner["metrics"]["ndcg@10"] - baseline["metrics"]["ndcg@10"]
        delta_r5   = winner["metrics"]["recall@5"] - baseline["metrics"]["recall@5"]
        lines.append(f"- Прирост NDCG@10 над baseline `e5-small`: **+{delta_ndcg:.3f}** ({delta_ndcg/max(baseline['metrics']['ndcg@10'],1e-6)*100:.0f}%)")
        lines.append(f"- Прирост Recall@5 над baseline `e5-small`: **+{delta_r5:.3f}**")
        lines.append(f"- Цена: latency {winner['latency_ms_per_query']:.0f}мс/q vs {baseline['latency_ms_per_query']:.0f}мс/q, +RAM {winner['peak_added_ram_mb']:.0f}МБ vs {baseline['peak_added_ram_mb']:.0f}МБ")
    lines.append("")
    lines.append("## Все модели")
    lines.append("")
    for r in results:
        lines.append(f"- **{r['model_key']}** (`{r['hf_id']}`, {r['dim']}D) — {r['notes']}")
    lines.append("")
    lines.append("## Методика")
    lines.append("")
    lines.append("1. **Корпус:** все чанки из `rag_chunks` кроме `auto_gelfand1971ru` (мусорный OCR).")
    lines.append("2. **Golden set:** случайные чанки, стратифицированные по source_id. Для каждого DeepSeek сгенерировал реалистичный студенческий вопрос (см. `infra/scripts/benchmark_data/golden_set.json`).")
    lines.append("3. **Retrieval:** косинусное сходство по нормированным эмбеддингам, top-10. Префиксы `query: ` / `passage: ` для семейства e5 — как требует документация модели.")
