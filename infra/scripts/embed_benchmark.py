"""
Embedding model benchmark on MindFlow's actual RAG corpus.

Compares 6 free open-source multilingual embedders on retrieval quality
using a golden set auto-generated by DeepSeek from the live corpus.

Stages (cached separately, resumable):
    1. corpus     — download rag_chunks from Supabase, drop garbage source(s)
    2. goldenset  — for N sampled chunks, ask DeepSeek to write a student-style
                    question whose answer lives in that chunk → (query, gt_id)
    3. models     — for each model: embed corpus + queries → top-K cosine →
                    Recall@K, MRR@10, NDCG@10, latency, peak RAM. Saved per-model.
    4. report     — render reports/embedding-benchmark.md from all collected JSON

Run:
    python3 infra/scripts/embed_benchmark.py --stage all
    python3 infra/scripts/embed_benchmark.py --stage models --only bge-m3
"""

