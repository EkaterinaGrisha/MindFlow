# ─── CLI ──────────────────────────────────────────────────────────────────────

def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", required=True,
                    choices=["all", "corpus", "goldenset", "models", "report"])
    ap.add_argument("--only", nargs="*", help="restrict --stage models to these keys")
    args = ap.parse_args()

    if args.stage in ("all", "corpus"):
        stage_corpus()
    if args.stage in ("all", "goldenset"):
        stage_goldenset()
    if args.stage in ("all", "models"):
        stage_models(only=args.only)
    if args.stage in ("all", "report"):
        stage_report()


if __name__ == "__main__":
    main()
