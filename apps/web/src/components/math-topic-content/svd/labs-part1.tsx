export default function SvdPart1LabView() {
  const [activeLab, setActiveLab] = useState<string>(SVD_PART1_LABS[0].id);
  const lab = SVD_PART1_LABS.find((item) => item.id === activeLab) ?? SVD_PART1_LABS[0];

  return (
    <LabShell
      title="Лаборатории SVD · Часть 1"
      intro="Каждая лаборатория открывается в отдельном окне ниже. Переключай вкладки слева направо и исследуй, как геометрия SVD проявляется в разных задачах: от трёхслойного разложения до «детектива» по сингулярным числам."
      labs={SVD_PART1_LABS}
      activeId={activeLab}
      onSelect={setActiveLab}
    >
      {lab.id === 'svd1-decompose' ? (
        <SVDDecomposeThreeStepsLab />
      ) : lab.id === 'svd1-orthogonal-axes' ? (
        <SVDOrthogonalAxesLab />
      ) : lab.id === 'svd1-rank1-layers' ? (
        <SVDRank1LayersLab />
      ) : lab.id === 'svd1-stretch' ? (
        <SVDStretchCoefficientsLab />
      ) : lab.id === 'svd1-detective' ? (
        <SVDDetectiveLab />
      ) : (
        <LabBody title="Лаборатория" question="Выберите лабораторию." mechanics={[]} explore={[]} insight="" />
      )}
    </LabShell>
  );
}
