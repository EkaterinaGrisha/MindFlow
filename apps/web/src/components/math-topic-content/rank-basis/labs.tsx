export default function RankBasisLabView({ onGoTheory }: { onGoTheory: () => void }) {
  const [activeLab, setActiveLab] = useState<string>(RANK_BASIS_LABS[0].id);
  const lab = RANK_BASIS_LABS.find((item) => item.id === activeLab) ?? RANK_BASIS_LABS[0];

  return (
    <div className="space-y-4">
      <LabShell
        title="Лаборатории: Ранг и базис"
        intro="Пять отдельных стендов: линейная оболочка, ранг через Гаусса, проверка базиса в ℝ³, визуализация ядра/образа и низкоранговое сжатие как мостик к SVD."
        labs={RANK_BASIS_LABS}
        activeId={activeLab}
        onSelect={setActiveLab}
      >
        {lab.id === 'rank-basis-span' ? (
          <SpanVisualizerLab />
        ) : lab.id === 'rank-basis-gauss' ? (
          <GaussianRankLab />
        ) : lab.id === 'rank-basis-checker' ? (
          <BasisCheckerLab />
        ) : lab.id === 'rank-basis-kernel-image' ? (
          <KernelImageLab />
        ) : lab.id === 'rank-basis-low-rank' ? (
          <LowRankApproximationLab />
        ) : (
          <LabBody title="Лаборатория" question="Выберите лабораторию." mechanics={[]} explore={[]} insight="" />
        )}
      </LabShell>
      <button onClick={onGoTheory} className="rounded-2xl border border-slate-200 bg-white px-4 py-2 text-sm font-bold text-slate-700 hover:border-indigo-300">
        Вернуться к теории
      </button>
    </div>
  );
}
